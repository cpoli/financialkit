r"""
Calibrating Heston to a smile
=============================

Heston's closed-form characteristic function is what made the model
usable in practice: a whole surface of strikes and maturities prices in
milliseconds, so its five parameters can be fitted to the market by
least squares. Each price error is divided by the option's Black-Scholes
vega, which turns it, to first order, into an implied-volatility error,

.. math::

   \min_{v_0, \kappa, \theta, \xi, \rho} \sum_i \left(\frac{C^{\text{Heston}}_i - C^{\text{mkt}}_i}{\mathcal{V}_i}\right)^2
   \approx \sum_i \left(\sigma^{\text{Heston}}_i - \sigma^{\text{mkt}}_i\right)^2,

without inverting the model's prices at every step. Here a synthetic
market is generated by a known Heston model, and the fit starts far
from it.
"""

# %%
import matplotlib.pyplot as plt
import numpy as np

from financialkit.stochastic_volatility import HestonModel, fourier_calibrate
from financialkit.stochastic_volatility.visualizers import plot_calibration

S, r, q = 100.0, 0.03, 0.01
maturities = np.array([0.25, 0.5, 1.0, 2.0])
K, T = np.meshgrid(np.linspace(75, 130, 12), maturities)
true = dict(v0=0.04, kappa=1.5, theta=0.06, xi=0.6, rho=-0.7)
x0 = dict(v0=0.02, kappa=3.0, theta=0.03, xi=0.3, rho=-0.2)

market = HestonModel(**true)
prices = np.array([market.price(S, k, t, r, q) for k, t in zip(K, maturities, strict=True)])
fit = fourier_calibrate(HestonModel, x0, S, K, T, r, q, prices=prices)
for name in true:
    print(f"{name:>5}: start {x0[name]:6.3f}   fitted {fit.params[name]:9.6f}   true {true[name]:6.3f}")
print(f"RMSE {fit.rmse:.1e} vol points after {fit.nfev} evaluations")
assert all(abs(fit.params[n] - v) < 1e-6 for n, v in true.items())
assert fit.rmse < 1e-6

# %%
# A noisy market
# --------------
#
# Real quotes carry bid-ask noise. With a quarter of a vol point of noise
# on each quote, the fit lands at the noise level, and the parameters the
# smile pins down well (the short-term variance :math:`v_0` and the skew
# :math:`\rho`) stay close to the truth.

rng = np.random.default_rng(0)
vols = np.array([market.implied_vol(S, k, t, r, q) for k, t in zip(K, maturities, strict=True)])
noisy = vols + 0.0025 * rng.standard_normal(vols.shape)
noisy_fit = fourier_calibrate(HestonModel, x0, S, K, T, r, q, vols=noisy)
print({n: round(v, 3) for n, v in noisy_fit.params.items()})
print(f"RMSE {noisy_fit.rmse:.3f} vol points")
assert 0.15 < noisy_fit.rmse < 0.3
assert abs(noisy_fit.params["v0"] - true["v0"]) < 0.005 and abs(noisy_fit.params["rho"] - true["rho"]) < 0.1

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))
plot_calibration(noisy_fit, ax=ax1)
for t in maturities:
    idx = noisy_fit.maturities == t
    ax2.plot(noisy_fit.strikes[idx], 100 * (noisy_fit.model_vols[idx] - noisy_fit.market_vols[idx]), "o-", ms=3, label=f"T = {t:g}")
ax2.axhline(0.0, color="k", lw=0.8)
ax2.set_xlabel("strike K")
ax2.set_ylabel("model minus market (vol points)")
ax2.legend()
fig.tight_layout()

plt.show()
